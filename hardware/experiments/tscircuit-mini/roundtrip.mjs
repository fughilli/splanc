import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import {KicadToCircuitJsonConverter} from 'kicad-to-circuit-json';
import {CircuitJsonToKicadPcbConverter} from 'circuit-json-to-kicad';
import {convertCircuitJsonToPcbSvg} from 'circuit-to-svg';
const [source,outDir]=process.argv.slice(2);
fs.mkdirSync(outDir,{recursive:true});
const content=fs.readFileSync(source,'utf8');
const c=new KicadToCircuitJsonConverter();
c.addFile(path.basename(source),content);
const start=performance.now();c.runUntilFinished();
const cj=c.getOutput();
const counts={};for(const item of cj)counts[item.type]=(counts[item.type]??0)+1;
fs.writeFileSync(path.join(outDir,'import.circuit.json'),JSON.stringify(cj,null,2));
fs.writeFileSync(path.join(outDir,'import.svg'),convertCircuitJsonToPcbSvg(cj));
const report={source:path.resolve(source),sha256:crypto.createHash('sha256').update(content).digest('hex'),counts,warnings:c.getWarnings(),stats:c.getStats(),importMs:performance.now()-start};
console.log(JSON.stringify(report,null,2));
fs.writeFileSync(path.join(outDir,'conversion-report.json'),JSON.stringify(report,null,2));
const exporter=new CircuitJsonToKicadPcbConverter(cj);exporter.runUntilFinished();
fs.writeFileSync(path.join(outDir,'roundtrip.kicad_pcb'),exporter.getOutputString());
fs.copyFileSync(source.replace(/\.kicad_pcb$/,'.kicad_pro'),path.join(outDir,'roundtrip.kicad_pro'));
console.log('Exported native roundtrip PCB');
