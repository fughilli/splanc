#!/usr/bin/env python3
"""Generates tests/testdata/tz_vectors.txt for tests/tz.rs from the host's tzdata.

For each zone: the POSIX rule tzdata itself uses past its transition table (the
footer line of the TZif file), then (utc_s, utc_offset_s) samples from Python's
zoneinfo: one second either side of every offset change in 2027..2060, plus
mid-January and mid-July of every year. Python's zoneinfo is an independent
evaluator, so the Rust parser and evaluator are checked against it.

    python3 firmware/clock/tools/gen_tz_vectors.py > firmware/clock/tests/testdata/tz_vectors.txt
"""
import datetime as dt
import sys
import zoneinfo

ZONES = [
    # Northern hemisphere, DST.
    "Europe/Berlin",
    "Europe/London",
    "Europe/Lisbon",
    "Europe/Kyiv",
    "America/New_York",
    "America/Chicago",
    "America/Denver",
    "America/Los_Angeles",
    "America/Anchorage",
    "America/Halifax",
    "America/St_Johns",
    "America/Havana",
    "Atlantic/Azores",
    "Atlantic/Canary",
    "America/Nuuk",
    "Asia/Jerusalem",
    "Africa/Cairo",
    "Antarctica/Troll",
    "Pacific/Honolulu",
    # Southern hemisphere, DST.
    "Australia/Sydney",
    "Australia/Adelaide",
    "Australia/Lord_Howe",
    "Pacific/Auckland",
    "Pacific/Chatham",
    "America/Santiago",
    "Pacific/Easter",
    # No DST.
    "UTC",
    "Asia/Tokyo",
    "Asia/Kolkata",
    "Asia/Kathmandu",
    "Asia/Shanghai",
    "America/Phoenix",
    "Africa/Johannesburg",
    "America/Sao_Paulo",
    "Pacific/Marquesas",
    "Pacific/Kiritimati",
    "Asia/Tehran",
    "Australia/Brisbane",
    "Africa/Casablanca",
]
FIRST, LAST = 2027, 2060


def footer(zone):
    with open(f"/usr/share/zoneinfo/{zone}", "rb") as f:
        return f.read().rstrip(b"\n").rsplit(b"\n", 1)[-1].decode()


def off(z, t):
    return int(dt.datetime.fromtimestamp(t, z).utcoffset().total_seconds())


def changes(z, lo, hi):
    """Every offset change in [lo, hi) to the second (hourly scan + bisection)."""
    out = []
    t = lo
    prev = off(z, t)
    while t < hi:
        n = t + 3600
        o = off(z, n)
        if o != prev:
            a, b = t, n
            while b - a > 1:
                m = (a + b) // 2
                if off(z, m) == prev:
                    a = m
                else:
                    b = m
            out.append(b)
            prev = o
        t = n
    return out


def main():
    utc = dt.timezone.utc
    print("# Generated by gen_tz_vectors.py from tzdata", end="")
    try:
        with open("/usr/share/zoneinfo/tzdata.zi") as f:
            print(" " + f.readline().split()[-1], end="")
    except OSError:
        pass
    print(". Zone lines: 'Z <iana> <posix rule>'; then '<utc_s> <offset_s>'.")
    for name in ZONES:
        z = zoneinfo.ZoneInfo(name)
        lo = int(dt.datetime(FIRST, 1, 1, tzinfo=utc).timestamp())
        hi = int(dt.datetime(LAST + 1, 1, 1, tzinfo=utc).timestamp())
        pts = set()
        for c in changes(z, lo, hi):
            pts.update((c - 1, c))
        for y in range(FIRST, LAST + 1):
            for m in (1, 7):
                pts.add(int(dt.datetime(y, m, 15, 12, tzinfo=utc).timestamp()))
        print(f"Z {name} {footer(name)}")
        for t in sorted(pts):
            print(t, off(z, t))


if __name__ == "__main__":
    sys.exit(main())
