"""esp-flasher-stub's per-chip JSON (text/data base64, their load addresses, the entry)
-> a C source with the segments as arrays, for c6_flasher.cpp.

    stub_to_c.py esp32c6.json out.c
"""

import base64
import json
import sys


def arr(name: str, data: bytes) -> str:
    rows = [", ".join(f"0x{b:02x}" for b in data[i : i + 16]) for i in range(0, len(data), 16)]
    return f"const unsigned char {name}[{len(data)}] = {{\n  " + ",\n  ".join(rows) + "\n};\n"


def main() -> None:
    d = json.load(open(sys.argv[1]))
    text = base64.b64decode(d["text"])
    data = base64.b64decode(d.get("data", ""))
    with open(sys.argv[2], "w") as f:
        f.write(
            "// GENERATED by stub_to_c.py from esp-flasher-stub (Apache-2.0 OR MIT); do not edit.\n"
        )
        f.write("#include <stdint.h>\n\n")
        f.write(arr("c6_stub_text", text))
        f.write(arr("c6_stub_data", data if data else b"\0"))
        f.write(f"const uint32_t c6_stub_text_len = {len(text)};\n")
        f.write(f"const uint32_t c6_stub_data_len = {len(data)};\n")
        f.write(f"const uint32_t c6_stub_text_start = 0x{d['text_start']:08x};\n")
        f.write(f"const uint32_t c6_stub_data_start = 0x{d.get('data_start', 0):08x};\n")
        f.write(f"const uint32_t c6_stub_entry = 0x{d['entry']:08x};\n")


if __name__ == "__main__":
    main()
