"""Emit the loader's trusted OTA keyring as a C++ header.

  gen_key_header.py --key 0=keys/release.pub --key 1=keys/backup.pub --out ota_key.h
  gen_key_header.py --lang rust --key 3=keys/max.pub --out ring.rs   (the MAX updater)

Each .pub holds a SEC1 uncompressed P-256 public key (65 bytes) as hex, with
optional `#` comment lines; the literal UNSET (a key not provisioned yet) yields an
entry with has=false, which never verifies anything. The key id is what a manifest
names in its flags (docs/design/ota.md "Key rotation").
"""

import argparse
import os
import re
import sys


def read_key(path):
    lines = [ln.strip() for ln in open(path) if ln.strip() and not ln.strip().startswith("#")]
    text = "".join(lines)
    if text == "UNSET":
        return None
    if not re.fullmatch(r"[0-9a-fA-F]{130}", text):
        sys.exit("gen_key_header: %s: want 130 hex chars (SEC1 uncompressed P-256) or UNSET" % path)
    key = bytes.fromhex(text)
    if key[0] != 0x04:
        sys.exit("gen_key_header: %s: not an uncompressed point (first byte 0x04)" % path)
    return key


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--key", action="append", required=True, help="ID=path")
    ap.add_argument("--out", required=True)
    ap.add_argument("--lang", choices=("cpp", "rust"), default="cpp")
    a = ap.parse_args()
    entries = []
    mask = 0
    for spec in a.key:
        kid, path = spec.split("=", 1)
        kid = int(kid)
        key = read_key(path)
        name = re.sub(r"\.pub$", "", os.path.basename(path))
        if key:
            mask |= 1 << kid
        body = ",\n      ".join(
            ", ".join("0x%02x" % b for b in (key or bytes(65))[i : i + 13])
            for i in range(0, 65, 13)
        )
        entries.append(
            '    {%d, "%s", %s, {\n      %s,\n    }},'
            % (kid, name, "true" if key else "false", body)
        )
    if a.lang == "rust":
        write_rust(a)
        return
    with open(a.out, "w") as f:
        f.write(
            "// Generated by //firmware/ota:gen_key_header. Do not edit.\n"
            "#pragma once\n#include <stdint.h>\n\n"
            "namespace ota_key {\n"
            "struct Key {\n  uint8_t id;\n  const char *name;\n"
            "  bool has;  // false: not provisioned (UNSET) -- verifies nothing\n"
            "  uint8_t pub[65];  // SEC1 uncompressed P-256\n};\n"
            "constexpr Key kRing[] = {\n%s\n};\n"
            "constexpr int kRingLen = sizeof(kRing) / sizeof(kRing[0]);\n"
            "// Bit n set: key id n is provisioned.\n"
            "constexpr uint32_t kRingMask = 0x%xu;\n"
            "}  // namespace ota_key\n" % ("\n".join(entries), mask)
        )


def write_rust(a):
    """The same ring as a Rust const (the Splanc MAX updater, pi/max_ota): a slice
    of (key id, name, SEC1 public key or None for UNSET)."""
    rows = []
    for spec in a.key:
        kid, path = spec.split("=", 1)
        key = read_key(path)
        name = re.sub(r"\.pub$", "", os.path.basename(path))
        val = "None" if key is None else "Some([%s])" % ", ".join("0x%02x" % b for b in key)
        rows.append('    (%d, "%s", %s),' % (int(kid), name, val))
    with open(a.out, "w") as f:
        f.write(
            "// Generated by //firmware/ota:gen_key_header --lang rust. Do not edit.\n"
            "/// The trusted keyring: (key id, name, SEC1 uncompressed P-256 or None = UNSET).\n"
            "pub const RING: &[(u8, &str, Option<[u8; 65]>)] = &[\n%s\n];\n" % "\n".join(rows)
        )


if __name__ == "__main__":
    main()
