/// The pattern-relevant subset of `CodeParams` (§7.6). The player derives it
/// with [`CodeSpec::derive`] (the same derivation the Python dev backend's
/// codebook.py runs through the C ABI) so both ends of `mapping_started` agree
/// by construction.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct CodeSpec {
    pub led_count: u32,
    /// Data-word width k (the Gray word FEC wraps): `data_bits(led_count)`,
    /// or wider for a pruned code book ([`SyncPattern::StaggerPilot`]).
    pub data_bits: u32,
    /// Coded BITS per cycle (data + FEC parity), sent log2(symbols) per frame.
    pub bits: u32,
    /// Data alphabet size: 2 or 4.
    pub symbols: u8,
    /// Sync frames ([`CodeSpec::sync_frames`]) + ceil(bits / log2(symbols)).
    pub cycle_frames: u32,
    /// SEC-DED FEC around the Gray data word.
    pub secded: bool,
    /// Where each LED's sync frames sit (`CodeParams.syncPattern`). v1
    /// ([`SyncPattern::OnOff`]) is the default from [`CodeSpec::derive`].
    pub sync: SyncPattern,
}

impl CodeSpec {
    /// The code-book derivation: `bits` from the LED count + FEC mode,
    /// `cycle_frames` from `bits` + the alphabet.
    pub const fn derive(led_count: u32, symbols: u8, secded: bool) -> Self {
        let bits = expected_bits(led_count, secded);
        CodeSpec {
            led_count,
            data_bits: data_bits(led_count),
            bits,
            symbols,
            cycle_frames: DATA_FRAME_OFFSET + data_frames(bits, symbols),
            secded,
            sync: SyncPattern::OnOff,
        }
    }

    /// The same fixture's code book under another sync pattern
    /// (`CodeParams.syncPattern`): [`CodeSpec::derive_sync`].
    pub fn with_sync(self, sync: SyncPattern) -> Self {
        CodeSpec::derive_sync(self.led_count, self.symbols, self.secded, sync)
    }

    /// The code-book derivation under a sync pattern. Unpruned patterns are
    /// [`CodeSpec::derive`] with the pattern set (same bits, same cycle).
    /// [`SyncPattern::StaggerPilot`] prunes the code book
    /// ([`stagger_valid`]): the data word widens one bit at a time until enough
    /// words survive for `led_count` ids, and the cycle is the palette pilot +
    /// the data frames. Counting costs one validity check per word of the
    /// final width (2^k; ~4096 for 1260 LEDs at 2 symbols) — once per capture.
    pub fn derive_sync(led_count: u32, symbols: u8, secded: bool, sync: SyncPattern) -> Self {
        let mut spec = CodeSpec { sync, ..CodeSpec::derive(led_count, symbols, secded) };
        if !sync.pruned() {
            return spec;
        }
        let mut k = spec.data_bits;
        loop {
            spec = CodeSpec::from_parts(led_count, k, symbols, secded, sync);
            if k >= 24 || stagger_count_valid(&spec) >= led_count {
                return spec;
            }
            k += 1;
        }
    }

    /// The code book a received `CodeParams` describes (`bits` as received;
    /// the data width k is recovered from it): no counting, O(1).
    pub const fn from_params(led_count: u32, bits: u32, symbols: u8, secded: bool, sync: SyncPattern) -> Self {
        let k = if secded { secded_data_bits(bits) } else { bits };
        CodeSpec {
            led_count,
            data_bits: k,
            bits,
            symbols,
            cycle_frames: sync_frames(sync, symbols) + data_frames(bits, symbols),
            secded,
            sync,
        }
    }

    const fn from_parts(led_count: u32, k: u32, symbols: u8, secded: bool, sync: SyncPattern) -> Self {
        let bits = if secded { secded_total_bits(k) } else { k };
        CodeSpec::from_params(led_count, bits, symbols, secded, sync)
    }

    /// Frames of the sync position: 2 (v1 white/green and the comparators), or
    /// the palette pilot's length ([`palette_pilot`]).
    pub const fn sync_frames(&self) -> u32 {
        sync_frames(self.sync, self.symbols)
    }

    pub const fn bits_per_symbol(&self) -> u32 {
        bits_per_symbol(self.symbols)
    }

    /// Data-frame count (last frame zero-padded in its high bit when odd).
    pub const fn data_frames(&self) -> u32 {
        data_frames(self.bits, self.symbols)
    }
}

/// Transmitted code-bit count implied by an LED count + FEC mode: the Gray
/// data word, plus the SEC-DED parity bits when `secded`.
pub const fn expected_bits(led_count: u32, secded: bool) -> u32 {
    let k = data_bits(led_count);
    if secded {
        secded_total_bits(k)
    } else {
        k
    }
}

/// Bits carried per data frame: log2 of the symbol alphabet (2 -> 1, 4 -> 2).
/// Only 2 and 4 are defined; callers validate the alphabet at their edge.
pub const fn bits_per_symbol(symbols: u8) -> u32 {
    if symbols == 2 {
        1
    } else {
        2
    }
}

/// Data-frame count for `bits` code bits: `ceil(bits / bits_per_symbol)`; the
/// last frame's high bit is zero-padded when `bits` is odd.
pub const fn data_frames(bits: u32, symbols: u8) -> u32 {
    bits.div_ceil(bits_per_symbol(symbols))
}

/// The TRANSMITTED codeword for `led_id`: `gray(id+1)`, SEC-DED-wrapped when
/// the spec says so. Bits are sent log2(symbols) per data frame, LSB first.
///
/// Under a pruned code book ([`SyncPattern::StaggerPilot`]) id `i` carries the
/// (i+1)-th valid coded index instead of `i + 1` ([`coded_index`]).
pub fn codeword(led_id: u32, spec: &CodeSpec) -> u32 {
    codeword_coded(coded_index(led_id, spec), spec)
}

/// The coded index `n` id `led_id` transmits as `gray(n)`: `id + 1`, or under
/// a pruned code book the (id+1)-th valid index ([`stagger_unrank`]; O(id) —
/// renderers walk ids in order with [`stagger_next`] instead).
pub fn coded_index(led_id: u32, spec: &CodeSpec) -> u32 {
    if spec.sync.pruned() {
        stagger_unrank(led_id, spec)
    } else {
        led_id + CODE_OFFSET
    }
}

/// The transmitted codeword of coded index `n`: `gray(n)`, SEC-DED-wrapped
/// when the spec says so.
pub fn codeword_coded(n: u32, spec: &CodeSpec) -> u32 {
    let data = gray(n);
    if spec.secded {
        secded_encode(data, spec.data_bits)
    } else {
        data
    }
}

/// The symbol VALUE `led_id` transmits in data frame `frame`.
pub fn symbol_at(led_id: u32, frame: u32, spec: &CodeSpec) -> u8 {
    symbol_of(codeword(led_id, spec), frame, spec)
}

/// The symbol VALUE coded index `n` transmits in data frame `frame`.
pub fn symbol_at_coded(n: u32, frame: u32, spec: &CodeSpec) -> u8 {
    symbol_of(codeword_coded(n, spec), frame, spec)
}

const fn symbol_of(cw: u32, frame: u32, spec: &CodeSpec) -> u8 {
    let bps = spec.bits_per_symbol();
    // Wrapping shift: a frame past the codeword is a caller bug; this keeps the
    // result well-defined (and identical to the JS `>>` the phone used to run).
    ((cw.wrapping_shr(frame.wrapping_mul(bps))) & ((1 << bps) - 1)) as u8
}

#[cfg(feature = "app")]
/// The outcome of decoding one observed cycle (see [`decode_cycle_symbols`]).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct CycleDecode {
    /// The decoded LED id, or `None` (see the flags for why).
    pub id: Option<u32>,
    /// SEC-DED corrected a single misread bit.
    pub corrected: bool,
    /// SEC-DED detected a double error — rejected, never miscorrected.
    pub uncorrectable: bool,
}

/// Pack one cycle's per-data-frame symbol values into the received code word
/// (`log2(symbols)` bits per frame, LSB first), masked to `spec.bits` (drops
/// the zero-padded high bit of an odd-width last frame).
#[cfg(feature = "app")]
pub fn cycle_code(symbols: &[u8], spec: &CodeSpec) -> u32 {
    let bps = spec.bits_per_symbol();
    let mut code: u32 = 0;
    for (d, &s) in symbols.iter().enumerate() {
        code |= (s as u32).wrapping_shl(d as u32 * bps);
    }
    code & 1u32.wrapping_shl(spec.bits).wrapping_sub(1)
}

#[cfg(feature = "app")]
/// Decode one cycle's per-data-frame symbol values into an LED id (the
/// phone's decode side of [`symbol_at`]).
///
/// `symbols[d]` is the observed symbol value in data frame `d` (the caller has
/// already verified the white/green sync delimiter). `spec` is the code-book AS
/// RECEIVED (`bits` is taken from it, not re-derived). `id` is `None` when the
/// frame count is wrong, the FEC detects an uncorrectable error, or the decoded
/// id is the reserved all-zero word / out of range.
pub fn decode_cycle_symbols(symbols: &[u8], spec: &CodeSpec) -> CycleDecode {
    let d = decode_cycle_coded(symbols, spec);
    // decode_gray(code) == 0 is the reserved all-zero word: a dark/noise artifact.
    // A pruned code book maps the coded index back to its rank (an index the
    // book excludes is not an id).
    let id = match d.id {
        Some(n) if spec.sync.pruned() => stagger_rank(n, spec),
        Some(n) => n.checked_sub(CODE_OFFSET),
        None => None,
    };
    let id = match id {
        Some(id) if id < spec.led_count => Some(id),
        _ => None,
    };
    CycleDecode { id, ..d }
}

#[cfg(feature = "app")]
/// [`decode_cycle_symbols`] up to the CODED INDEX: `id` holds `n` (the word
/// gray(n) carried, after SEC-DED), not mapped to an LED id. For a pruned book
/// the id is `n`'s rank, which [`stagger_rank`] finds by walking the book
/// (O(n) validity checks); a decoder that holds the book's id <-> index table
/// (the phone does, from [`stagger_unrank`]'s walk) maps `n` itself in O(1).
pub fn decode_cycle_coded(symbols: &[u8], spec: &CodeSpec) -> CycleDecode {
    let none = CycleDecode { id: None, corrected: false, uncorrectable: false };
    if symbols.len() as u32 != spec.data_frames() {
        return none;
    }
    let mut code = cycle_code(symbols, spec);
    let mut corrected = false;
    if spec.secded {
        match secded_decode(code, spec.data_bits) {
            (Some(data), c) => {
                code = data;
                corrected = c;
            }
            (None, _) => {
                return CycleDecode { id: None, corrected: false, uncorrectable: true };
            }
        }
    }
    CycleDecode { id: Some(decode_gray(code)), corrected, uncorrectable: false }
}

// ---------------------------------------------------------------------------
// Diffuse-capture striding (docs/design/strided-capture.md). On a diffused
// fixture, lighting every LED every frame blends adjacent spots into one blob;
// instead the player lights only a sparse, ≥ `spacing`-separated subset per phase
// and the phone rotates the phase across epochs. Two jobs, deliberately split:
//
//   1. COVERAGE — `spacing` phases, uniform stride, offset +1 per phase: phase `o`
//      lights `{o, o+S, o+2S, …}`; the union over `o = 0..S-1` is every LED.
//   2. FUSION — `S-1` sparse "bridge" phases forming a star through class 0: the
//      bridge for class `j` co-lights class-0 anchor reps (every `A·S`-th LED) and
//      class-`j` reps in class 0's gaps, so all lit spots stay ≥ `S` apart (needs
//      `A ≥ 3`). The LED co-observation graph then has diameter 2.
//
// Every lit LED still shows its own full hue code, so ids stay absolute and fuse
// across phases — striding changes WHICH LEDs are lit, never the code.
// ---------------------------------------------------------------------------

/// Total phases in one schedule: `spacing` coverage + `spacing-1` bridges; `1`
/// when striding is disabled (`spacing <= 1`, the legacy all-lit pattern).
pub const fn stride_phase_count(spacing: u32) -> u32 {
    if spacing <= 1 {
        1
    } else {
        2 * spacing - 1
    }
}

/// The coverage phases are `0 .. spacing-1`; the rest are bridges.
pub const fn stride_is_coverage(phase: u32, spacing: u32) -> bool {
    phase < spacing
}

/// Is `led` lit in `phase` under the stride schedule? `spacing <= 1` ⇒ always lit.
/// Out-of-range phases wrap (the caller may pass a running counter). `anchor_density`
/// is clamped up to 3 (below it a bridge's lit spots can fall closer than `spacing`).
pub fn stride_lit(led: u32, phase: u32, spacing: u32, anchor_density: u32) -> bool {
    let s = spacing;
    if s <= 1 {
        return true;
    }
    let n = 2 * s - 1;
    let ph = phase % n;
    if ph < s {
        // Coverage: uniform stride-`s` grid at offset `ph`.
        return led % s == ph;
    }
    // Bridge linking class 0 with class `j` (j = 1 .. s-1).
    let j = ph - s + 1;
    let a = if anchor_density < 3 { 3 } else { anchor_density };
    let period = a * s;
    let m = led % period;
    // Class-0 anchor rep at the block start; class-`j` rep in the block's mid gap.
    m == 0 || m == (a / 2) * s + j
}

// ---------------------------------------------------------------------------
// Rolling stride (docs/design/rolling-stride.md). The phased schedule above
// steps EVERY LED at once (the phone sends `configure { stridePhase }`), so
// every track dies together. The rolling schedule is instead a pure function
// of (LED, pattern-clock frame): the lamp and the phone evaluate the same
// function, and nothing is ever reconfigured to stride.
//
//   - BLOCKS of `B = A·S` LEDs (A clamped up to 3, as for the bridges). Within
//     a block, the lit LEDs are the stride-`S` grid at the block's OFFSET
//     `o`, and `o` steps 0, 1, …, S-1, 0, … once per DWELL of `W = D·C`
//     frames (D = `dwell_cycles` code cycles of C frames). The class of LED
//     `x` is `x mod S`, so each LED is lit for one dwell per PERIOD `S·W`.
//   - Each block runs that clock shifted by its own offset: block `b+1` steps
//     ONE CODE CYCLE (C frames) BEFORE block `b` ([`rolling_block_shift`]),
//     a short wave travelling toward LED 0. Any D consecutive blocks thus
//     spread their steps evenly over the dwell, and neighbouring offsets never
//     invert except at the wrap (S-1 -> 0), for one cycle.
//   - An LED is lit for its OWN whole code cycles only (under hue code v2 its
//     cycle is rotated by `stagger_phase`): from the first own-cycle start in
//     its dwell to the last own cycle that ends inside it. A track is never
//     cut mid-cycle.
//   - BOUNDARY RULE (owner decision D-173): two LEDs less than `S` apart in
//     neighbouring blocks (only at the offset wrap) never light together; the
//     one whose lit interval started LATER stays dark for every own cycle of
//     its that overlaps the other's interval (ties: the lower index keeps).
//     The earlier one is never interrupted, so no live track is cut.
//
// Bridge phases do not exist in rolling mode: neighbouring blocks sit at
// different offsets all the time, so every frame co-lights LEDs of several
// classes and the co-observation graph is connected by construction (the
// design doc's analysis and `solver` scenario `strideMode: rolling` pin it).
// ---------------------------------------------------------------------------

/// The default rolling dwell `D`, in code cycles (design doc: D = 4 leaves
/// staggered LEDs D-1 = 3 whole own cycles per dwell, one more than the
/// decoder's two confirmations need; D = 3 leaves exactly two).
pub const ROLLING_DWELL_DEFAULT: u32 = 4;
/// The smallest dwell the kernel runs; smaller requests are clamped up. A
/// 2-cycle dwell leaves a staggered LED one whole own cycle (no decode), and
/// the block-start LED that yields at the wrap none at all.
pub const ROLLING_DWELL_MIN: u32 = 3;
/// The largest dwell accepted (bounds the i64 schedule arithmetic; far longer
/// than any useful dwell).
pub const ROLLING_DWELL_MAX: u32 = 64;

/// Rolling-stride geometry: everything [`stride_lit_rolling`] needs besides
/// the code spec and the frame. Built once per capture (cold).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct RollingStride {
    /// `S`, the stride spacing (`<= 1` lights every LED).
    pub spacing: u32,
    /// `A`: the block is `A·S` LEDs; clamped up to 3.
    pub anchor_density: u32,
    /// `D`: dwell length in code cycles; clamped to
    /// [`ROLLING_DWELL_MIN`]..=[`ROLLING_DWELL_MAX`].
    pub dwell_cycles: u32,
    /// Physical LEDs on the strip (no neighbour past it exists). 0 = unbounded.
    pub led_count: u32,
    /// Group capture: LED `i` transmits code-book id `i + code_offset`, so its
    /// own cycle is `stagger_phase(i + code_offset)`. 0 for a solo capture.
    pub code_offset: u32,
}

impl RollingStride {
    pub const fn new(spacing: u32, anchor_density: u32, dwell_cycles: u32, led_count: u32, code_offset: u32) -> Self {
        RollingStride { spacing, anchor_density, dwell_cycles, led_count, code_offset }
    }
    /// The block length `B = A·S` (A clamped up to 3).
    pub const fn block_len(&self) -> u32 {
        let a = if self.anchor_density < 3 { 3 } else { self.anchor_density };
        a * self.spacing
    }
    /// `D` as the kernel runs it.
    pub const fn dwell(&self) -> u32 {
        let d = self.dwell_cycles;
        if d < ROLLING_DWELL_MIN {
            ROLLING_DWELL_MIN
        } else if d > ROLLING_DWELL_MAX {
            ROLLING_DWELL_MAX
        } else {
            d
        }
    }
    /// Frames per dwell (`W = D·C`).
    pub const fn dwell_frames(&self, spec: &CodeSpec) -> u32 {
        self.dwell() * cycle_len(spec)
    }
    /// Frames per period (`S·W`): every LED lights once per period.
    pub const fn period_frames(&self, spec: &CodeSpec) -> u32 {
        let s = if self.spacing < 1 { 1 } else { self.spacing };
        s * self.dwell_frames(spec)
    }
}

const fn cycle_len(spec: &CodeSpec) -> u32 {
    if spec.cycle_frames < 1 {
        1
    } else {
        spec.cycle_frames
    }
}

const fn div_floor(a: i64, b: i64) -> i64 {
    let q = a / b;
    if (a % b != 0) && ((a < 0) != (b < 0)) {
        q - 1
    } else {
        q
    }
}

const fn mod_floor(a: i64, b: i64) -> i64 {
    let r = a % b;
    if r < 0 {
        r + b
    } else {
        r
    }
}

/// Block `b`'s clock shift in frames, in `[0, S·W)`: its dwell `k` spans
/// frames `[k·W + shift, (k+1)·W + shift)` and lights class `k mod S`.
/// Block `b+1` runs one code cycle ahead of block `b` (`shift(b+1) =
/// shift(b) - C`, mod the period). Part of the wire format: the lamp and the
/// phone must agree (the goldens pin it).
pub const fn rolling_block_shift(block: u32, rs: &RollingStride, spec: &CodeSpec) -> u32 {
    let p = rs.period_frames(spec) as u64;
    let c = cycle_len(spec) as u64;
    ((p - (block as u64 * c) % p) % p) as u32
}

/// LED `led`'s first CANDIDATE lit interval `[start, end)` (pattern-clock
/// frames since the epoch) that ends after frame `t`: its class's dwell in its
/// block's clock, clipped to frames >= 0 and trimmed to the LED's own whole
/// code cycles. `start` may be after `t` (the LED is dark at `t`). The
/// boundary rule ([`stride_lit_rolling`]) is applied on top.
pub fn rolling_interval(led: u32, t: i64, spec: &CodeSpec, rs: &RollingStride) -> (i64, i64) {
    let s = rs.spacing.max(1) as i64;
    let c = cycle_len(spec) as i64;
    let w = rs.dwell_frames(spec) as i64;
    let b = rs.block_len().max(1);
    let shift = rolling_block_shift(led / b, rs, spec) as i64;
    let class = (led as i64) % s;
    let own = stagger_phase(led.wrapping_add(rs.code_offset), spec) as i64;
    let t = if t < 0 { 0 } else { t };
    // The dwell containing t, then back to the latest dwell of this LED's class.
    let k0 = div_floor(t - shift, w);
    let mut k = k0 - mod_floor(k0 - class, s);
    loop {
        let ws = k * w + shift;
        let ws = if ws < 0 { 0 } else { ws };
        let we = (k + 1) * w + shift;
        let start = ws + mod_floor(own - ws, c);
        if we > start {
            let cycles = (we - start) / c;
            let end = start + cycles * c;
            if cycles > 0 && end > t {
                return (start, end);
            }
        }
        k += s;
    }
}

/// Is LED `led` lit at pattern-clock frame `seq` (absolute frames since the
/// pattern epoch, NOT reduced modulo the cycle) under the rolling stride?
/// `spacing <= 1` lights every LED. Allocation-free; the player calls it per
/// LED per rendered frame. Interior LEDs cost one [`rolling_interval`]; the
/// LEDs within `S-1` of a block boundary also evaluate their neighbours across
/// it (the boundary rule).
pub fn stride_lit_rolling(led: u32, seq: u32, spec: &CodeSpec, rs: &RollingStride) -> bool {
    let s = rs.spacing;
    if s <= 1 {
        return true;
    }
    if rs.led_count > 0 && led >= rs.led_count {
        return false;
    }
    let t = seq as i64;
    let (start, _end) = rolling_interval(led, t, spec, rs);
    if start > t {
        return false;
    }
    let c = cycle_len(spec) as i64;
    let b = rs.block_len();
    let block = led / b;
    // The own cycle containing t: the LED yields it whole or not at all.
    let cs = start + ((t - start) / c) * c;
    let ce = cs + c;
    let lo = led.saturating_sub(s - 1);
    let hi = led as u64 + (s - 1) as u64;
    let mut yy = lo as u64;
    while yy <= hi && yy <= u32::MAX as u64 {
        let y = yy as u32;
        yy += 1;
        // Same block: one class at a time, S apart; never a conflict.
        let other_block = y / b != block;
        let exists = rs.led_count == 0 || y < rs.led_count;
        if y != led && other_block && exists {
            let (ys, _ye) = rolling_interval(y, cs, spec, rs);
            if ys < ce && (ys < start || (ys == start && y < led)) {
                return false;
            }
        }
    }
    true
}

// ---------------------------------------------------------------------------
// Hue code v2 phase 2: staggered cycles with a pilot (docs/design/hue-code-v2.md).
//
// v1 (`SyncPattern::OnOff`) shows the white/green sync delimiter on EVERY LED
// at the same frame. Under a staggered pattern LED `id` runs its cycle rotated
// by `phase(id) = (id * S + h(id / C)) mod C` (C = cycle_frames, S =
// [`stagger_step`], h a per-block offset: [`stagger_phase`]), so
// at any frame only ~L/C of the LEDs are in their sync position, and that
// position shows a PILOT instead of white:
//
//   - `StaggerPilot` (the wire value "stagger_pilot"): a short fixed sequence
//     of symbols FROM THE ACTIVE PALETTE ([`palette_pilot`]), at the data's own
//     drive. No hue is reserved: data keeps the full alphabet. Every channel
//     the palette uses is lit in one pilot frame and dark in another, so each
//     pilot gives a per-channel on/off calibration. The pilot is unique by
//     CODE-BOOK PRUNING ([`stagger_valid`]): an id whose whole cycle, read
//     cyclically, contains the pilot anywhere but at its sync position is
//     excluded, and ids map to the surviving coded indices in order
//     ([`stagger_unrank`] / [`stagger_rank`]).
//   - `StaggerWhite` / `StaggerGreenMagenta`: simulator comparators only (no
//     wire values): v1's white -> green, and the first phase-2 draft's green ->
//     magenta (a reserved hue), both staggered over the unpruned v1 book.
//
// The rotation lives here, inside `color_index_for_frame`, on the CODED id
// (the id the LED transmits, i.e. `led + code_offset`): callers keep passing
// the global cycle frame.
// ---------------------------------------------------------------------------

/// The sync layout of a cycle (`CodeParams.syncPattern`).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
#[repr(u8)]
pub enum SyncPattern {
    /// v1, "on_off": every LED shows white then green in cycle frames 0, 1.
    OnOff = 0,
    /// "stagger_pilot": per-LED phase rotation; the sync position shows the
    /// palette pilot; the code book is pruned so the pilot is unique.
    StaggerPilot = 1,
    /// Simulation comparator only: staggered v1 white -> green.
    StaggerWhite = 2,
    /// Simulation comparator only: staggered green -> magenta.
    StaggerGreenMagenta = 3,
}

impl SyncPattern {
    /// The ABI code: 0 on_off, 1 stagger_pilot, 2 stagger_white,
    /// 3 stagger_gm (anything else is treated as on_off).
    pub const fn from_code(code: u32) -> Self {
        match code {
            1 => SyncPattern::StaggerPilot,
            2 => SyncPattern::StaggerWhite,
            3 => SyncPattern::StaggerGreenMagenta,
            _ => SyncPattern::OnOff,
        }
    }

    pub const fn is_staggered(self) -> bool {
        !matches!(self, SyncPattern::OnOff)
    }

    /// The code book is pruned for pilot uniqueness ([`stagger_valid`]).
    pub const fn pruned(self) -> bool {
        matches!(self, SyncPattern::StaggerPilot)
    }
}

/// The 2-symbol palette pilot: blue, blue, red, red, blue (symbol values of
/// [`SYMBOL_COLORS_2`]). Red and blue are each lit in one pilot frame and dark
/// in another. Five frames: the shortest binary pilot that leaves
/// comfortably more than 1260 ids (2443 of a 12-bit book; 4 frames would need
/// a 13-bit one and give a cycle as long).
pub const PILOT_2: [u8; 5] = [0, 0, 1, 1, 0];
/// The 4-symbol palette pilot: blue, yellow, magenta (values of
/// [`SYMBOL_COLORS_4`]). Blue and yellow are complementary (every channel lit
/// in one, dark in the other); magenta makes it three frames, which keeps
/// 1863 of the 11-bit book's 2047 ids (a 2-frame pilot keeps 1265).
pub const PILOT_4: [u8; 3] = [0, 2, 1];

/// The palette pilot (symbol values) for an alphabet; anything but 2 is 4.
pub const fn palette_pilot(symbols: u8) -> &'static [u8] {
    if symbols == 2 {
        &PILOT_2
    } else {
        &PILOT_4
    }
}

/// Sync-position frames of a cycle: the palette pilot's length under
/// `StaggerPilot`, 2 otherwise.
pub const fn sync_frames(sync: SyncPattern, symbols: u8) -> u32 {
    match sync {
        SyncPattern::StaggerPilot => palette_pilot(symbols).len() as u32,
        _ => DATA_FRAME_OFFSET,
    }
}

/// The colour of sync-position frame `j` (< [`sync_frames`]).
pub const fn sync_color(sync: SyncPattern, symbols: u8, j: u32) -> Color {
    match sync {
        SyncPattern::StaggerPilot => symbol_color(symbols, palette_pilot(symbols)[j as usize]),
        SyncPattern::StaggerGreenMagenta => {
            if j == 0 {
                Color::Green
            } else {
                Color::Magenta
            }
        }
        _ => {
            if j == 0 {
                Color::White
            } else {
                Color::Green
            }
        }
    }
}

/// Is coded index `n` in the pruned code book? Its cycle stream (the pilot,
/// then the data symbols of `codeword_coded(n)`) must not contain the pilot
/// at any cyclic offset other than 0, so a track that finds the pilot has
/// found its sync position. `n = 0` (the reserved all-zero word) never is.
/// O(C) for almost every offset (the first symbol already differs).
pub fn stagger_valid(n: u32, spec: &CodeSpec) -> bool {
    if n == 0 || (spec.data_bits < 32 && n >> spec.data_bits != 0) {
        return false;
    }
    let pilot = palette_pilot(spec.symbols);
    let l = pilot.len() as u32;
    let c = spec.cycle_frames;
    let cw = codeword_coded(n, spec);
    let at = |p: u32| -> u8 {
        if p < l {
            pilot[p as usize]
        } else {
            symbol_of(cw, p - l, spec)
        }
    };
    let mut o = 1;
    while o < c {
        let mut j = 0;
        while j < l && at((o + j) % c) == pilot[j as usize] {
            j += 1;
        }
        if j == l {
            return false;
        }
        o += 1;
    }
    true
}

/// The next valid coded index after `n` (the walk renderers use: id `i+1`
/// carries `stagger_next(index of id i)`), or `u32::MAX` past the book.
pub fn stagger_next(mut n: u32, spec: &CodeSpec) -> u32 {
    let end = if spec.data_bits >= 32 { u32::MAX } else { 1u32 << spec.data_bits };
    loop {
        n += 1;
        if n >= end {
            return u32::MAX;
        }
        if stagger_valid(n, spec) {
            return n;
        }
    }
}

/// The coded index of id `id` in a pruned book: the (id+1)-th valid index.
/// O(id) validity checks; `u32::MAX` past the book.
pub fn stagger_unrank(id: u32, spec: &CodeSpec) -> u32 {
    let mut n = 0;
    let mut i = 0;
    while i <= id {
        n = stagger_next(n, spec);
        if n == u32::MAX {
            return n;
        }
        i += 1;
    }
    n
}

/// The id coded index `n` carries in a pruned book (its rank among the valid
/// indices), or `None` if the book excludes it. O(n) validity checks.
pub fn stagger_rank(n: u32, spec: &CodeSpec) -> Option<u32> {
    if !stagger_valid(n, spec) {
        return None;
    }
    let mut r = 0;
    let mut m = 1;
    while m < n {
        if stagger_valid(m, spec) {
            r += 1;
        }
        m += 1;
    }
    Some(r)
}

/// How many ids a pruned book of this width holds.
pub fn stagger_count_valid(spec: &CodeSpec) -> u32 {
    let end = if spec.data_bits >= 32 { u32::MAX } else { 1u32 << spec.data_bits };
    let mut count = 0;
    let mut n = 1;
    while n < end {
        if stagger_valid(n, spec) {
            count += 1;
        }
        n += 1;
    }
    count
}

const fn gcd(mut a: u32, mut b: u32) -> u32 {
    while b != 0 {
        let t = a % b;
        a = b;
        b = t;
    }
    a
}

/// The stagger step S for a cycle of `cycle_frames` frames: the integer
/// coprime with C nearest C/Φ (Φ the golden ratio). Coprime, so `id * S mod C`
/// visits every phase equally often (a flat per-frame pilot census);
/// golden-ratio, so ids that are neighbours on a strip land far apart in phase.
/// The design pins S = 11, 7, 5, 5 for C = 18, 10, 8, 6; this rule reproduces
/// them and extends to every C (the test pins the table). C < 2 -> 1.
pub const fn stagger_step(cycle_frames: u32) -> u32 {
    let c = cycle_frames;
    if c < 2 {
        return 1;
    }
    // C/Φ = C * 0.6180339887…, compared in 1e9 fixed point (no floats on the
    // firmware path; C is far below the overflow bound).
    let target = c as u64 * 618_033_989;
    let mut best = 1u32;
    let mut best_err = u64::MAX;
    let mut s = 1;
    while s < c {
        if gcd(s, c) == 1 {
            let v = s as u64 * 1_000_000_000;
            let err = if v > target { v - target } else { target - v };
            if err < best_err {
                best_err = err;
                best = s;
            }
        }
        s += 1;
    }
    best
}

/// lowbias32 (C. Wellons' 32-bit integer finaliser): a fixed, well-mixed
/// u32 -> u32 bijection. Integer-only, so it runs as is on the firmware path.
const fn mix32(mut x: u32) -> u32 {
    x ^= x >> 16;
    x = x.wrapping_mul(0x7feb_352d);
    x ^= x >> 15;
    x = x.wrapping_mul(0x846c_a68b);
    x ^= x >> 16;
    x
}

/// The key the block offsets are drawn under. Part of the wire format: a
/// change re-phases every staggered LED (the goldens pin it).
const PHASE_KEY: u32 = 0x5eed;

/// Circular distance between phases `a` and `b` in Z_c.
const fn circ_dist(a: u32, b: u32, c: u32) -> u32 {
    let d = (a % c + c - b % c) % c;
    if d < c - d {
        d
    } else {
        c - d
    }
}

/// The free (unconstrained) offset of block `q`: a keyed hash mod C.
const fn block_offset_free(q: u32, c: u32) -> u32 {
    mix32(q ^ PHASE_KEY) % c
}

/// The phase offset `h(q)` of id block `q` (ids `q*C .. q*C + C - 1`).
///
/// Even blocks take the keyed hash ([`block_offset_free`]). An odd block takes
/// the first value of its own hash-ordered probe sequence that keeps both of
/// its block boundaries spread: the last id of block `q - 1` and the first id
/// of block `q` (and the last of `q` and the first of `q + 1`) land at least
/// `C/8 + 1` frames apart in phase. Its neighbours are even, so this needs no
/// recursion: O(1) hashes and at most C probes (each constraint excludes at
/// most `2d - 1` of the C values, and `2(2d - 1) < C` for every C >= 3, so a
/// value always exists; C < 3 falls back to the hash).
const fn block_offset(q: u32, c: u32, s: u32) -> u32 {
    let v = block_offset_free(q, c);
    if q % 2 == 0 {
        return v;
    }
    let lo = block_offset_free(q - 1, c);
    let hi = block_offset_free(q + 1, c);
    let d = c / 8 + 1;
    let mut t = 0;
    while t < c {
        let x = (v + t) % c;
        // Boundary phase steps: (last of q-1) -> (first of q) is s + x - lo,
        // (last of q) -> (first of q+1) is s + hi - x (the in-block step is s).
        if circ_dist(s + x, lo, c) >= d && circ_dist(s + hi, x, c) >= d {
            return x;
        }
        t += 1;
    }
    v
}

/// The phase rotation of id `led_id` under a staggered pattern (its sync
/// position starts at global cycle frame `phase`), 0 for v1:
///
/// `φ(id) = (id·S + h(id div C)) mod C`
///
/// Within a block of C consecutive ids it is the golden-ratio stagger (ids
/// one apart are S apart in phase, and the block covers every phase once:
/// a flat pilot census). The per-block offset `h` ([`block_offset`]) makes φ
/// NON-LINEAR across blocks: the linear `(id·S) mod C` gave every pair of
/// ids a multiple of C apart the same phase, and the SEC-DED stitches that
/// decode to a wrong id cluster at exactly those offsets, so the phase check
/// passed them 2.5x more often than chance (docs/design/hue-code-v2.md,
/// "Non-linear pilot phase"). Any φ that is a function of `id mod C` (a
/// permutation of the linear phase, say) keeps that flaw.
pub const fn stagger_phase(led_id: u32, spec: &CodeSpec) -> u32 {
    if !spec.sync.is_staggered() || spec.cycle_frames == 0 {
        return 0;
    }
    let c = spec.cycle_frames;
    let s = stagger_step(c);
    ((led_id % c) * s + block_offset(led_id / c, c, s)) % c
}

/// The LED's own cycle frame at global cycle frame `frame_index`: 0, 1 = the
/// sync position, `DATA_FRAME_OFFSET + d` = data frame `d`. Equals
/// `frame_index` under v1.
pub const fn local_frame(led_id: u32, frame_index: u32, spec: &CodeSpec) -> u32 {
    let c = spec.cycle_frames;
    if !spec.sync.is_staggered() || c == 0 {
        return frame_index;
    }
    (frame_index % c + c - stagger_phase(led_id, spec)) % c
}

/// A palette entry. The data palette per alphabet is [`symbol_color`]; white
/// and green are reserved for the sync delimiter (cyan is unused: it scores on
/// the green sync axis).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
#[repr(u8)]
pub enum Color {
    White = 0,
    Green = 1,
    Red = 2,
    Blue = 3,
    Magenta = 4,
    Yellow = 5,
}

impl Color {
    /// The 255-scale RGB the driver emits for this palette entry.
    pub const fn rgb(self) -> Rgb {
        match self {
            Color::White => WHITE,
            Color::Green => GREEN,
            Color::Red => RED,
            Color::Blue => BLUE,
            Color::Magenta => MAGENTA,
            Color::Yellow => YELLOW,
        }
    }
}

/// Symbol value -> palette entry for an alphabet (see [`SYMBOL_COLORS_2`] /
/// [`SYMBOL_COLORS_4`]); `symbols` other than 2 is treated as 4.
pub const fn symbol_color(symbols: u8, value: u8) -> Color {
    const P2: [Color; 2] = [Color::Blue, Color::Red];
    const P4: [Color; 4] = [Color::Blue, Color::Magenta, Color::Yellow, Color::Red];
    if symbols == 2 {
        P2[value as usize & 1]
    } else {
        P4[value as usize & 3]
    }
}

/// The palette entry `led_id` shows in cycle frame `frame_index` (the phone
/// renders this onto its virtual wall; the player maps it through
/// [`Color::rgb`]).
///
/// `frame_index` is the GLOBAL cycle frame; under a staggered
/// [`SyncPattern`] the LED's own frame is rotated by [`stagger_phase`] first.
/// A pruned book looks the id's coded index up in O(id)
/// ([`coded_index`]); renderers that walk every LED use
/// [`color_index_for_frame_coded`] with [`stagger_next`].
pub fn color_index_for_frame(led_id: u32, frame_index: u32, spec: &CodeSpec) -> Color {
    color_index_for_frame_coded(led_id, coded_index(led_id, spec), frame_index, spec)
}

/// [`color_index_for_frame`] with the id's coded index `n` supplied by the
/// caller (`coded_index(led_id, spec)`).
pub fn color_index_for_frame_coded(led_id: u32, n: u32, frame_index: u32, spec: &CodeSpec) -> Color {
    let l = spec.sync_frames();
    let j = local_frame(led_id, frame_index, spec);
    if j < l {
        sync_color(spec.sync, spec.symbols, j)
    } else {
        symbol_color(spec.symbols, symbol_at_coded(n, j - l, spec))
    }
}

/// The color `led_id` shows in cycle frame `frame_index`.
///
/// `frame_index` must be within the cycle (callers index with
/// `frame % cycle_frames`); out-of-range is a firmware logic bug.
pub fn color_for_frame(led_id: u32, frame_index: u32, spec: &CodeSpec) -> Rgb {
    debug_assert!(frame_index < spec.cycle_frames, "frame outside cycle");
    color_index_for_frame(led_id, frame_index, spec).rgb()
}

// ---------------------------------------------------------------------------
// Pattern-clock timing (design doc §8.2, `app` feature), the phone's float model: map a
// server-clock time (ms, f64) to a position in the repeating cycle. The decoder
// and the virtual LED wall both use it, so a wall pixel and the phone's
// bit-window sampling can never disagree about which frame is showing. (The
// players' render loops run the same clock in integer microseconds.)
// ---------------------------------------------------------------------------

#[cfg(feature = "app")]
pub mod timing {
    /// IEEE `floor` (as JS `Math.floor`) without libm (no_std): exact for
    /// every f64 (all values with |x| >= 2^52 are already integral), -0.0 and
    /// NaN preserved.
    // The negated compare is deliberate: it is also true for NaN, which floor
    // must pass through unchanged.
    #[allow(clippy::neg_cmp_op_on_partial_ord)]
    fn floor(x: f64) -> f64 {
        if !(x.abs() < 4_503_599_627_370_496.0) {
            return x; // already integral (|x| >= 2^52), or NaN/inf
        }
        let t = x as i64 as f64;
        let f = if t > x { t - 1.0 } else { t };
        // Keep -0.0 for x = -0.0 (Math.floor(-0) is -0).
        if f == 0.0 && x.is_sign_negative() {
            -0.0
        } else {
            f
        }
    }

    /// Length of one full cycle in milliseconds.
    pub fn cycle_ms(cycle_frames: u32, bit_period_ms: f64) -> f64 {
        cycle_frames as f64 * bit_period_ms
    }

    /// Non-negative phase in ms within the current cycle.
    pub fn phase_ms(t_server_ms: f64, epoch_ms: f64, cycle_frames: u32, bit_period_ms: f64) -> f64 {
        let cycle = cycle_ms(cycle_frames, bit_period_ms);
        let mut phase = (t_server_ms - epoch_ms) % cycle;
        if phase < 0.0 {
            phase += cycle;
        }
        phase
    }

    /// Cycle frame index (`0..cycle_frames-1`) showing at server time `t_server_ms`.
    pub fn frame_index_at(t_server_ms: f64, epoch_ms: f64, cycle_frames: u32, bit_period_ms: f64) -> f64 {
        let idx = floor(phase_ms(t_server_ms, epoch_ms, cycle_frames, bit_period_ms) / bit_period_ms);
        // Guard the phase == cycle_ms float edge case.
        let last = cycle_frames as f64 - 1.0;
        if idx > last {
            last
        } else {
            idx
        }
    }

    /// Which cycle (may be negative before the epoch) contains `t_server_ms`.
    pub fn cycle_index_at(t_server_ms: f64, epoch_ms: f64, cycle_frames: u32, bit_period_ms: f64) -> f64 {
        floor((t_server_ms - epoch_ms) / cycle_ms(cycle_frames, bit_period_ms))
    }

    /// Fraction `[0, 1)` through the current frame window (the decoder discards
    /// samples near window edges: bit transitions + rolling-shutter smear).
    pub fn frame_fraction_at(t_server_ms: f64, epoch_ms: f64, cycle_frames: u32, bit_period_ms: f64) -> f64 {
        let phase = phase_ms(t_server_ms, epoch_ms, cycle_frames, bit_period_ms);
        (phase % bit_period_ms) / bit_period_ms
    }
}

