    #[test]
    fn timing_walks_the_cycle_and_wraps() {
        use timing::*;
        let (cf, bp) = (8u32, 100.0);
        assert_eq!(cycle_ms(cf, bp), 800.0);
        let epoch = 5000.0;
        for k in 0..8 {
            let t = epoch + k as f64 * 100.0 + 50.0;
            assert_eq!(frame_index_at(t, epoch, cf, bp), k as f64);
            assert_eq!(frame_index_at(t + 800.0, epoch, cf, bp), k as f64, "next cycle");
        }
        // Before the epoch: the previous cycle's last frame.
        assert_eq!(frame_index_at(epoch - 50.0, epoch, cf, bp), 7.0);
        assert_eq!(cycle_index_at(epoch - 50.0, epoch, cf, bp), -1.0);
        let e = 1234.5;
        assert_eq!(cycle_index_at(e + 10.0, e, cf, bp), 0.0);
        assert_eq!(cycle_index_at(e + 799.9, e, cf, bp), 0.0);
        assert_eq!(cycle_index_at(e + 800.1, e, cf, bp), 1.0);
        assert_eq!(cycle_index_at(e + 8000.0, e, cf, bp), 10.0);
        assert_eq!(frame_fraction_at(25.0, 0.0, cf, bp), 0.25);
        assert_eq!(frame_fraction_at(175.0, 0.0, cf, bp), 0.75);
        assert!(frame_fraction_at(99.99, 0.0, cf, bp) < 1.0);
        // phase is non-negative and below the cycle.
        for i in -50..50 {
            let p = phase_ms(i as f64 * 37.3, 0.0, cf, bp);
            assert!((0.0..800.0).contains(&p), "phase {p}");
        }
    }

    #[test]
    fn stride_coverage_partitions_and_bridges_stay_apart() {
        for s in 2..8u32 {
            for a in [0u32, 3, 4, 5] {
                let n = 200;
                assert_eq!(stride_phase_count(s), 2 * s - 1);
                // Coverage phases partition the LEDs.
                for led in 0..n {
                    let hits = (0..s).filter(|&p| stride_lit(led, p, s, a)).count();
                    assert_eq!(hits, 1, "S={s} led {led}");
                }
                // Every phase keeps lit LEDs >= S apart.
                for p in 0..stride_phase_count(s) {
                    let lit: Vec<u32> = (0..n).filter(|&l| stride_lit(l, p, s, a)).collect();
                    assert!(lit.windows(2).all(|w| w[1] - w[0] >= s), "S={s} A={a} phase {p}");
                    assert_eq!(stride_is_coverage(p, s), p < s);
                }
                // Phases wrap.
                assert_eq!(stride_lit(5, 0, s, a), stride_lit(5, stride_phase_count(s), s, a));
            }
        }
        assert_eq!(stride_phase_count(1), 1);
        assert!(stride_lit(7, 3, 1, 3), "S<=1 lights every LED");
    }
