//! The hue-code kernel: THE one implementation of Splanc's LED colour code
//! (design doc §8.1, docs/esp32-led-mapping-plan.md Phase 4a).
//!
//! no_std and zero-dependency, so the same source serves every consumer:
//!
//! - every Rust player (C6/P4 firmware via //firmware/player, the Pi
//!   `pi/player_rs`, the Mac host player) links this crate directly;
//! - the phone app runs it as a few-KB wasm module (`abi/kernel_abi.rs`, built
//!   by `//web:code_kernel_wasm`), behind the thin typed wrappers in
//!   `web/src/code/{gray,fec,stride,timing}.ts`;
//! - the Python dev backend (`pi/server/server/codebook.py`) sizes code-books
//!   through the same C ABI, loaded with ctypes.
//!
//! Encode side (what LEDs show) and decode side (what the phone reads back)
//! both live here, so a firmware/phone disagreement cannot be written.
//!
//! Firmware links only the render path. The decode side — Gray inverse,
//! SEC-DED decode, cycle decode, the phone's float pattern clock — is behind
//! the `app` crate feature, which only the app-side targets enable
//! (`//firmware/pattern:pattern_app`: the wasm/ctypes ABI, the golden
//! generator, the unit tests). `//firmware/pattern:pattern`, the target every
//! player links, compiles without it. The
//! golden fixtures under `testdata/` are generated by `gen_golden` from this
//! crate and pin it against accidental change.
//!
//! The cycle: `[white ALL_ON][green ALL_OFF]` sync delimiter, then
//! `ceil(bits / log2(symbols))` data frames. Every LED is lit EVERY frame at
//! constant brightness — the code is carried entirely by color, which is
//! exactly the per-LED-RGB shape the ESP32 RMT output wants.

#![no_std]

/// 255-scale RGB, the driver-facing color type.
pub type Rgb = (u8, u8, u8);

pub const WHITE: Rgb = (255, 255, 255);
pub const GREEN: Rgb = (0, 255, 0);
pub const RED: Rgb = (255, 0, 0);
pub const BLUE: Rgb = (0, 0, 255);
pub const MAGENTA: Rgb = (255, 0, 255);
pub const YELLOW: Rgb = (255, 255, 0);

/// Symbol value -> color for `symbols=2` (bit 0 -> blue, bit 1 -> red).
pub const SYMBOL_COLORS_2: [Rgb; 2] = [BLUE, RED];
/// Symbol value -> color for `symbols=4`: the hue-adjacent path
/// blue(240°) -> magenta(300°) -> red(0°) -> yellow(60°) carries
/// binary-reflected-Gray bit pairs 00, 01, 11, 10, so the dominant misread
/// (adjacent hues) flips exactly one bit — which SEC-DED corrects.
pub const SYMBOL_COLORS_4: [Rgb; 4] = [BLUE, MAGENTA, YELLOW, RED];

/// Codewords carry `id + CODE_OFFSET`: the all-zero data word is
/// reserved-invalid (LED 0 would otherwise be a decode magnet).
pub const CODE_OFFSET: u32 = 1;

/// Cycle-frame indices of the sync delimiter; data frame d is frame 2+d.
pub const FRAME_ALL_ON: u32 = 0;
pub const FRAME_ALL_OFF: u32 = 1;
pub const DATA_FRAME_OFFSET: u32 = 2;

/// Binary-reflected Gray code.
#[inline]
pub const fn gray(i: u32) -> u32 {
    i ^ (i >> 1)
}

#[cfg(feature = "app")]
/// Inverse of [`gray`].
pub const fn decode_gray(mut value: u32) -> u32 {
    let mut result = 0;
    while value != 0 {
        result ^= value;
        value >>= 1;
    }
    result
}

/// Gray data-word width for `led_count` LEDs: `ceil(log2(led_count + 1))`,
/// minimum 1 (codewords carry id + 1).
pub const fn data_bits(led_count: u32) -> u32 {
    // ceil(log2(n)) for n = led_count + CODE_OFFSET >= 2.
    let n = led_count + CODE_OFFSET;
    if n <= 2 {
        1
    } else {
        32 - (n - 1).leading_zeros()
    }
}

// ---------------------------------------------------------------------------
// Extended-Hamming SEC-DED.
//
// Layout (canonical):
// - Data word: `k` bits (bit 0 = LSB).
// - Inner Hamming code, 1-indexed positions `1..k+r`, `r` minimal with
//   `2^r >= k + r + 1`; power-of-two positions hold even parity, the rest hold
//   data bits in increasing order.
// - One overall even-parity bit over the inner word (extends distance to 4),
//   transmitted LAST. Transmitted bit `j` = inner position `j+1`.
//
// Used as SEC-DED: single bit-frame errors are corrected, double errors are
// detected and the cycle rejected — never miscorrected (a d=4 guarantee). The
// raw Gray code-book has Hamming distance 1, so without it one decisive
// misread decodes to a valid WRONG id.
// ---------------------------------------------------------------------------

/// Number of Hamming parity bits `r` for `k` data bits (excluding the overall
/// parity bit): the smallest `r` with `2^r >= k + r + 1`.
pub const fn secded_parity_bits(k: u32) -> u32 {
    let mut r = 1;
    while (1 << r) < k + r + 1 {
        r += 1;
    }
    r
}

/// Total transmitted code bits for `k` data bits: `k + r + 1`.
pub const fn secded_total_bits(k: u32) -> u32 {
    k + secded_parity_bits(k) + 1
}

const fn is_pow2(x: u32) -> bool {
    x & (x - 1) == 0
}

/// Encode a `k`-bit data word into the transmitted codeword. Bit `j` of the
/// result is the value of transmission frame `j`.
pub fn secded_encode(data: u32, k: u32) -> u32 {
    debug_assert!(data >> k == 0, "data word does not fit in k bits");
    let r = secded_parity_bits(k);
    let m_inner = k + r;
    // Data bits at non-power-of-two inner positions 1..=m_inner.
    let mut word: u32 = 0;
    let mut bit = 0;
    let mut pos = 1;
    while pos <= m_inner {
        if !is_pow2(pos) {
            if (data >> bit) & 1 != 0 {
                word |= 1 << (pos - 1);
            }
            bit += 1;
        }
        pos += 1;
    }
    // Even parity at each power-of-two position over the positions it covers.
    let mut p_log = 0;
    while p_log < r {
        let p = 1 << p_log;
        let mut parity = 0;
        let mut pos = 1;
        while pos <= m_inner {
            if pos & p != 0 && (word >> (pos - 1)) & 1 != 0 {
                parity ^= 1;
            }
            pos += 1;
        }
        if parity != 0 {
            word |= 1 << (p - 1);
        }
        p_log += 1;
    }
    // Overall even parity over the inner word, transmitted last.
    if word.count_ones() & 1 != 0 {
        word |= 1 << m_inner;
    }
    word
}

#[cfg(feature = "app")]
/// Decode a received codeword: `(Some(data), corrected)` on success, or
/// `(None, false)` when a double error is detected (uncorrectable by design).
pub fn secded_decode(mut word: u32, k: u32) -> (Option<u32>, bool) {
    let r = secded_parity_bits(k);
    let m_inner = k + r;
    debug_assert!(word >> (m_inner + 1) == 0, "codeword too wide");
    let mut syndrome: u32 = 0;
    for pos in 1..=m_inner {
        if (word >> (pos - 1)) & 1 != 0 {
            syndrome ^= pos;
        }
    }
    let overall_ok = word.count_ones() & 1 == 0;
    let mut corrected = false;
    if syndrome == 0 {
        if !overall_ok {
            corrected = true; // the overall parity bit itself flipped
        }
    } else if overall_ok {
        return (None, false); // double error
    } else {
        if syndrome > m_inner {
            return (None, false); // multi-error signature
        }
        word ^= 1 << (syndrome - 1);
        corrected = true;
    }
    let mut data = 0;
    let mut bit = 0;
    for pos in 1..=m_inner {
        if !is_pow2(pos) {
            if (word >> (pos - 1)) & 1 != 0 {
                data |= 1 << bit;
            }
            bit += 1;
        }
    }
    (Some(data), corrected)
}

