//! Emit the hue-code golden fixtures from the kernel itself.
//!
//!     bazel run //firmware/pattern:goldens_update   # rewrite testdata/*.json
//!
//! (`//firmware/pattern:goldens` diff-tests the checked-in files against this
//! output.) The goldens are regression pins, not a cross-language contract: the
//! kernel IS the only implementation, so a diff here means the wire changed —
//! deliberate (hue-code v2) or a bug. JSON is written in the 2-space layout the
//! fixtures have always had, so a no-op change is byte-identical.
//!
//! Usage: gen_golden secded16 | secded16_sym4 | stride

use ledmapper_pattern as pat;
use std::fmt::Write as _;

/// A tiny JSON value with insertion-ordered objects.
enum J {
    Num(u64),
    Str(String),
    Arr(Vec<J>),
    Obj(Vec<(&'static str, J)>),
}

fn write(out: &mut String, v: &J, indent: usize) {
    let pad = |n: usize| " ".repeat(n);
    match v {
        J::Num(n) => write!(out, "{n}").unwrap(),
        J::Str(s) => {
            out.push('"');
            for c in s.chars() {
                match c {
                    '"' => out.push_str("\\\""),
                    '\\' => out.push_str("\\\\"),
                    c if c.is_ascii() && !c.is_ascii_control() => out.push(c),
                    c => write!(out, "\\u{:04x}", c as u32).unwrap(),
                }
            }
            out.push('"');
        }
        J::Arr(items) if items.is_empty() => out.push_str("[]"),
        J::Arr(items) => {
            out.push_str("[\n");
            for (i, item) in items.iter().enumerate() {
                out.push_str(&pad(indent + 2));
                write(out, item, indent + 2);
                out.push_str(if i + 1 < items.len() { ",\n" } else { "\n" });
            }
            out.push_str(&pad(indent));
            out.push(']');
        }
        J::Obj(fields) => {
            out.push_str("{\n");
            for (i, (k, item)) in fields.iter().enumerate() {
                write!(out, "{}\"{k}\": ", pad(indent + 2)).unwrap();
                write(out, item, indent + 2);
                out.push_str(if i + 1 < fields.len() { ",\n" } else { "\n" });
            }
            out.push_str(&pad(indent));
            out.push('}');
        }
    }
}

fn nums(it: impl IntoIterator<Item = u32>) -> J {
    J::Arr(it.into_iter().map(|n| J::Num(n as u64)).collect())
}

fn letter(c: pat::Color) -> char {
    match c {
        pat::Color::White => 'W',
        pat::Color::Green => 'G',
        pat::Color::Red => 'R',
        pat::Color::Blue => 'B',
        pat::Color::Magenta => 'M',
        pat::Color::Yellow => 'Y',
    }
}

/// A 16-LED SEC-DED code-book at the given alphabet: header, Gray table,
/// codewords, per-frame symbol values and the full color plan.
fn hue_golden(symbols: u8) -> J {
    let spec = pat::CodeSpec::derive(16, symbols, true);
    let n = spec.led_count;
    J::Obj(vec![
        (
            "comment",
            J::Str(
                "Generated by //firmware/pattern:gen_golden from the hue-code kernel \
                 (firmware/pattern, the only implementation: firmware players link it, the \
                 phone runs it as wasm). A regression pin: a diff means the wire changed. \
                 Codewords are secded_encode(gray(id+1), k): extended Hamming d=4 around the \
                 Gray data word, transmitted log2(symbols) bits per frame. Palette letters: W \
                 white (ALL_ON reference), G green (ALL_OFF sync), R red, B blue, M magenta, Y \
                 yellow."
                    .to_string(),
            ),
        ),
        ("ledCount", J::Num(n as u64)),
        ("dataBits", J::Num(pat::data_bits(n) as u64)),
        ("bits", J::Num(spec.bits as u64)),
        ("symbols", J::Num(symbols as u64)),
        ("cycleFrames", J::Num(spec.cycle_frames as u64)),
        ("fec", J::Str("secded".to_string())),
        ("gray", nums((0..n).map(pat::gray))),
        ("codewords", nums((0..n).map(|id| pat::codeword(id, &spec)))),
        (
            "symbolValues",
            J::Arr(
                (0..n)
                    .map(|id| nums((0..spec.data_frames()).map(|f| pat::symbol_at(id, f, &spec) as u32)))
                    .collect(),
            ),
        ),
        (
            "palette",
            J::Str((0..symbols).map(|v| letter(pat::symbol_color(symbols, v))).collect()),
        ),
        (
            "colorPlan",
            J::Arr(
                (0..spec.cycle_frames)
                    .map(|f| J::Str((0..n).map(|id| letter(pat::color_index_for_frame(id, f, &spec))).collect()))
                    .collect(),
            ),
        ),
    ])
}

/// The diffuse-capture stride schedule: the lit set per phase for a few
/// (ledCount, spacing, anchorDensity) cases (docs/gen_figures.py draws it).
fn stride_golden() -> J {
    let cases = [(32u32, 3u32, 3u32), (64, 4, 3), (50, 5, 4)];
    J::Obj(vec![(
        "cases",
        J::Arr(
            cases
                .iter()
                .map(|&(n, s, a)| {
                    let pc = pat::stride_phase_count(s);
                    J::Obj(vec![
                        ("ledCount", J::Num(n as u64)),
                        ("spacing", J::Num(s as u64)),
                        ("anchorDensity", J::Num(a as u64)),
                        ("phaseCount", J::Num(pc as u64)),
                        (
                            "phases",
                            J::Arr(
                                (0..pc).map(|ph| nums((0..n).filter(|&led| pat::stride_lit(led, ph, s, a)))).collect(),
                            ),
                        ),
                    ])
                })
                .collect(),
        ),
    )])
}

fn main() {
    let which = std::env::args().nth(1).unwrap_or_else(|| "secded16".to_string());
    let v = match which.as_str() {
        "secded16" => hue_golden(2),
        "secded16_sym4" => hue_golden(4),
        "stride" => stride_golden(),
        other => {
            eprintln!("unknown golden {other:?} (secded16 | secded16_sym4 | stride)");
            std::process::exit(1);
        }
    };
    let mut out = String::new();
    write(&mut out, &v, 0);
    println!("{out}");
}
